const express = require("express");
const os = require("os");
const crypto = require("crypto");
const client = require("prom-client");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());
app.use(express.static("public"));

// Prometheus Metrics Setup
const collectDefaultMetrics = client.collectDefaultMetrics;
collectDefaultMetrics({ register: client.register });

const httpRequestCounter = new client.Counter({
  name: "http_requests_total",
  help: "Total number of HTTP requests",
  labelNames: ["method", "route", "status"]
});

const shortenCounter = new client.Counter({
  name: "url_shorten_total",
  help: "Total number of URLs shortened"
});

const redirectCounter = new client.Counter({
  name: "url_redirect_total",
  help: "Total number of URL redirections"
});

// Middleware to record request metrics
app.use((req, res, next) => {
  res.on("finish", () => {
    httpRequestCounter.inc({
      method: req.method,
      route: req.route ? req.route.path : req.path,
      status: res.statusCode
    });
  });
  next();
});

const urlStore = {};

// Health check endpoint (for K8s liveness & readiness probes)
app.get("/health", (req, res) => {
  res.status(200).send("UP");
});

// Prometheus metrics scrape endpoint
app.get("/metrics", async (req, res) => {
  try {
    res.set("Content-Type", client.register.contentType);
    res.end(await client.register.metrics());
  } catch (err) {
    res.status(500).end(err);
  }
});

// API: shorten URL
app.post("/shorten", (req, res) => {
  const { url } = req.body;
  if (!url) return res.status(400).json({ error: "URL required" });

  const code = crypto.randomBytes(3).toString("hex");
  urlStore[code] = { url, clicks: 0, createdAt: new Date().toISOString() };
  shortenCounter.inc();

  res.json({
    shortUrl: `/${code}`,
    fullShortUrl: `${req.protocol}://${req.get("host")}/${code}`,
    code: code,
    pod: os.hostname()
  });
});

// Redirect
app.get("/:code", (req, res) => {
  const entry = urlStore[req.params.code];
  if (!entry) return res.status(404).send("Not found");

  entry.clicks++;
  redirectCounter.inc();
  res.redirect(entry.url);
});

// Stats
app.get("/stats/all", (req, res) => {
  res.json({
    pod: os.hostname(),
    totalUrls: Object.keys(urlStore).length,
    urls: urlStore
  });
});

// Load generator (CPU intensive for HPA demonstration)
app.get("/load", (req, res) => {
  const start = Date.now();
  while (Date.now() - start < 300) {
    Math.sqrt(Math.random());
  }
  res.send(`Load generated by pod ${os.hostname()}`);
});

app.listen(PORT, () => {
  console.log(`Server running on port ${PORT} (pod: ${os.hostname()})`);
});
